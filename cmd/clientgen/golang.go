package main

import (
	"bytes"
	"fmt"
	"go/format"
	"maps"
	"path"
	"slices"
	"strconv"
	"strings"

	"github.com/sirkostya009/rr/gen"
)

type goRenderer struct {
	body bytes.Buffer
	std  map[string]struct{}
	pkgs map[string]struct{}
}

func renderGo(root *gen.API) ([]byte, error) {
	g := &goRenderer{std: map[string]struct{}{"context": {}}, pkgs: map[string]struct{}{}}

	b := &g.body
	b.WriteString("type Client struct {\n\tc *conn\n\n")
	for _, m := range root.Mounts {
		fmt.Fprintf(b, "\t%s %[1]s\n", groupName(m.API))
	}
	b.WriteString("}\n\nfunc wrap(c *conn) *Client {\n\treturn &Client{\n\t\tc: c,\n")
	for _, m := range root.Mounts {
		fmt.Fprintf(b, "\t\t%s: %[1]s{c},\n", groupName(m.API))
	}
	b.WriteString("\t}\n}\n")

	for _, rt := range root.Routes {
		if err := g.method(rt, "cl *Client", "cl.c"); err != nil {
			return nil, err
		}
	}
	for _, m := range root.Mounts {
		name := groupName(m.API)
		fmt.Fprintf(b, "\n// %s calls the routes of %s.%s.\ntype %[1]s struct{ c *conn }\n", name, m.API.Pkg.Name, m.API.Name)
		for _, rt := range m.API.Routes {
			if err := g.method(rt, "g "+name, "g.c"); err != nil {
				return nil, err
			}
		}
	}

	var out bytes.Buffer
	fmt.Fprintf(&out, "// Code generated by clientgen from %s. DO NOT EDIT.\n\npackage client\n\nimport (\n", root.Pkg.Path)
	for _, p := range slices.Sorted(maps.Keys(g.std)) {
		fmt.Fprintf(&out, "\t%q\n", p)
	}
	out.WriteByte('\n')
	for _, p := range slices.Sorted(maps.Keys(g.pkgs)) {
		fmt.Fprintf(&out, "\t%q\n", p)
	}
	out.WriteString(")\n\n")
	out.Write(g.body.Bytes())
	return format.Source(out.Bytes())
}

func (g *goRenderer) method(rt *gen.Route, recv, conn string) error {
	if err := check(rt); err != nil {
		return err
	}
	where := rt.API.Name + "." + rt.Handler

	params := []string{"ctx context.Context"}
	var url []string
	lit := ""
	for _, s := range rt.Segments {
		if s.Kind == gen.SegLit {
			lit += "/" + s.Lit
			continue
		}
		p := s.Param
		if p.Name == "ctx" || p.Name == "body" || p.Name == strings.Fields(recv)[0] {
			return fmt.Errorf("%s: param {%s} shadows a name the client uses", where, p.Name)
		}
		typ, err := g.goType(p.Type)
		if err != nil {
			return fmt.Errorf("%s: {%s}: %w", where, p.Name, err)
		}
		params = append(params, p.Name+" "+typ)
		url = append(url, strconv.Quote(lit+"/"), g.segment(p))
		lit = ""
	}
	if lit != "" || url == nil {
		url = append(url, strconv.Quote(lit))
	}
	urlExpr := strings.Join(url, " + ")

	call := fmt.Sprintf("%s.do(ctx, %q, %s, nil)", conn, rt.Method, urlExpr)
	if body := rt.Body(); body != nil {
		typ, err := g.goType(gen.TypeRef{Pkg: body.Type.Pkg, Name: body.Type.Name})
		if err != nil {
			return fmt.Errorf("%s: body: %w", where, err)
		}
		send := "send"
		if manyBody(body) {
			typ, send = "[]"+typ, "sendMany"
		}
		params = append(params, "body "+typ)
		call = fmt.Sprintf("%s.%s(ctx, %q, %s, body)", conn, send, rt.Method, urlExpr)
	}

	b := &g.body
	b.WriteByte('\n')
	if rt.Doc != "" {
		for line := range strings.SplitSeq(rt.Doc, "\n") {
			b.WriteString(strings.TrimRight("// "+line, " "))
			b.WriteByte('\n')
		}
		b.WriteString("//\n")
		fmt.Fprintf(b, "// %s %s\n", rt.Method, rt.Path)
	} else {
		fmt.Fprintf(b, "// %s sends %s %s.\n", rt.Handler, rt.Method, rt.Path)
	}
	sig := fmt.Sprintf("func (%s) %s(%s)", recv, rt.Handler, strings.Join(params, ", "))

	if rt.Result == nil {
		fmt.Fprintf(b, "%s error {\n\treturn %s.none()\n}\n", sig, call)
		return nil
	}
	elem, err := g.goType(gen.TypeRef{Pkg: rt.Result.Pkg, Name: rt.Result.Name, Node: rt.Result.Node})
	if err != nil {
		return fmt.Errorf("%s: result: %w", where, err)
	}
	if rt.Result.Slice {
		fmt.Fprintf(b, "%s ([]%s, error) {\n\treturn %s.many[%s]()\n}\n", sig, elem, call, elem)
	} else {
		fmt.Fprintf(b, "%s (%s, error) {\n\treturn %s.one[%s]()\n}\n", sig, elem, call, elem)
	}
	return nil
}

// goType names a builtin or a named type, importing its package.
func (g *goRenderer) goType(t gen.TypeRef) (string, error) {
	if t.Ptr || t.Slice {
		return "", fmt.Errorf("unsupported type %s", t.Expr)
	}
	if t.Pkg == "" {
		if t.Name == "" {
			return "", fmt.Errorf("unsupported type %s", t.Expr)
		}
		return t.Name, nil
	}
	g.pkgs[t.Pkg] = struct{}{}
	return path.Base(t.Pkg) + "." + t.Name, nil
}

// segment renders a path param as text. A named type is assumed to print
// itself with String.
func (g *goRenderer) segment(p *gen.Param) string {
	switch {
	case p.Rest:
		return p.Name
	case p.Type.Pkg != "":
		g.std["net/url"] = struct{}{}
		return "url.PathEscape(" + p.Name + ".String())"
	}
	switch p.Type.Name {
	case "int":
		g.std["strconv"] = struct{}{}
		return "strconv.Itoa(" + p.Name + ")"
	case "bool":
		g.std["strconv"] = struct{}{}
		return "strconv.FormatBool(" + p.Name + ")"
	case "float64":
		g.std["strconv"] = struct{}{}
		return "strconv.FormatFloat(" + p.Name + ", 'g', -1, 64)"
	case "float32":
		g.std["strconv"] = struct{}{}
		return "strconv.FormatFloat(float64(" + p.Name + "), 'g', -1, 32)"
	}
	g.std["net/url"] = struct{}{}
	return "url.PathEscape(" + p.Name + ")"
}
