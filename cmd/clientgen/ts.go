const tsHeader = "// Code generated by clientgen. DO NOT EDIT."

// writeTS writes client.ts, the routes, and types.ts, every type they carry.
// A type is declared in the direction it travels: a body as the server decodes
// it, a result as the server encodes it. One that travels both ways gets an
// Input twin for its body shape.
func writeTS(root *gen.API, dir string) error {
	var routes []*gen.Route
	pkgs := map[string]struct{}{}
	for rt := range root.Served() {
		if err := check(rt); err != nil {
			return err
		}
		routes = append(routes, rt)
		if b := rt.Body(); b != nil {
			pkgs[b.Type.Pkg] = struct{}{}
		}
		if rt.Result != nil && rt.Result.Pkg != "" {
			pkgs[rt.Result.Pkg] = struct{}{}
		}
	}
	types, err := ggen.Load(slices.Sorted(maps.Keys(pkgs))...)
	if err != nil {
		return err
	}

	t := &tsTypes{set: types, in: map[*ggen.TypeDecl]struct{}{}, out: map[*ggen.TypeDecl]struct{}{}}
	for _, rt := range routes {
		if b := rt.Body(); b != nil {
			d, err := t.decl(b.Type.Pkg, b.Type.Name)
			if err != nil {
				return fmt.Errorf("%s.%s: body: %w", rt.API.Name, rt.Handler, err)
			}
			t.reach(d.In())
		}
		if r := rt.Result; r != nil && r.Pkg != "" {
			d, err := t.decl(r.Pkg, r.Name)
			if err != nil {
				return fmt.Errorf("%s.%s: result: %w", rt.API.Name, rt.Handler, err)
			}
			t.reach(d.Out())
		}
	}
	if err := t.write(dir); err != nil {
		return err
	}

	return os.WriteFile(filepath.Join(dir, "client.ts"), renderTSClient(root, t), 0o644) //nolint:gosec // a source file, world-readable like the rest
}

type tsTypes struct {
	set     *ggen.Set
	in, out map[*ggen.TypeDecl]struct{}
	used    map[string]struct{}
}

func (t *tsTypes) decl(pkg, name string) (*ggen.TypeDecl, error) {
	if d := t.set.Type(pkg, name); d != nil {
		return d, nil
	}
	return nil, fmt.Errorf("%s.%s has no //ggen:generate", pkg, name)
}

// reach marks a shape and everything it references as needed in its mode.
func (t *tsTypes) reach(s *ggen.Shape) {
	seen := t.out
	if s.Mode == ggen.In {
		seen = t.in
	}
	if _, ok := seen[s.Decl]; ok {
		return
	}
	seen[s.Decl] = struct{}{}
	for _, f := range s.Fields {
		t.reachType(f.Type, s.Mode)
	}
	t.reachType(s.Alias, s.Mode)
	t.reachType(s.Rest, s.Mode)
}

func (t *tsTypes) reachType(typ *ggen.Type, mode ggen.Mode) {
	if typ == nil {
		return
	}
	if typ.Ref != nil {
		if mode == ggen.In {
			t.reach(typ.Ref.In())
		} else {
			t.reach(typ.Ref.Out())
		}
	}
	t.reachType(typ.Elem, mode)
	t.reachType(typ.Key, mode)
	for _, o := range typ.OneOf {
		t.reachType(o, mode)
	}
}

func (t *tsTypes) name(d *ggen.TypeDecl, mode ggen.Mode) string {
	if _, both := t.out[d]; both && mode == ggen.In {
		return d.Name + "Input"
	}
	return d.Name
}

func (t *tsTypes) write(dir string) error {
	out := ggen.NewOutput(dir)
	f := out.File("types.ts", ts.New(ts.Header(tsHeader), ts.ImportExt(".ts"), ts.Indent("  ")))
	for _, d := range slices.Concat(t.set.Types(), t.set.Enums()) {
		if _, ok := t.out[d]; ok {
			f.Place(d.Out(), t.name(d, ggen.Out))
		}
		if _, ok := t.in[d]; ok {
			f.Place(d.In(), t.name(d, ggen.In))
		}
	}
	if err := out.Write(); err != nil {
		return err
	}
	if issues := out.Report().Issues; len(issues) > 0 {
		msgs := make([]string, len(issues))
		for i, is := range issues {
			msgs[i] = is.String()
		}
		return fmt.Errorf("not expressible in typescript:\n%s", strings.Join(msgs, "\n"))
	}
	return nil
}

// ref is the TypeScript name of a route's body or result, recorded as an
// import of the client.
func (t *tsTypes) ref(tr gen.TypeRef, mode ggen.Mode) string {
	if tr.Pkg == "" {
		return tsBuiltin(tr.Name)
	}
	n := t.name(t.set.Type(tr.Pkg, tr.Name), mode)
	t.used[n] = struct{}{}
	return n
}

func renderTSClient(root *gen.API, t *tsTypes) []byte {
	t.used = map[string]struct{}{}
	var body bytes.Buffer
	for _, rt := range root.Routes {
		tsMethod(&body, rt, t, "    ")
	}
	for _, m := range root.Mounts {
		fmt.Fprintf(&body, "    %s: {\n", lowerCamel(groupName(m.API)))
		for _, rt := range m.API.Routes {
			tsMethod(&body, rt, t, "      ")
		}
		body.WriteString("    },\n")
	}

	var b bytes.Buffer
	fmt.Fprintf(&b, "%s\n\n", tsHeader)
	b.WriteString("import { type Options, transport } from \"./runtime.ts\";\n")
	if len(t.used) > 0 {
		fmt.Fprintf(&b, "import type { %s } from \"./types.ts\";\n", strings.Join(slices.Sorted(maps.Keys(t.used)), ", "))
	}
	b.WriteString("\nexport { HttpError, type Options } from \"./runtime.ts\";\nexport type * from \"./types.ts\";\n\n")
	b.WriteString("export type Client = ReturnType<typeof createClient>;\n\n")
	fmt.Fprintf(&b, "/** Calls the routes of %s.%s. */\n", root.Pkg.Name, root.Name)
	b.WriteString("export function createClient(options: Options = {}) {\n  const t = transport(options);\n  return {\n")
	b.Write(body.Bytes())
	b.WriteString("  };\n}\n")
	return b.Bytes()
}

func tsMethod(b *bytes.Buffer, rt *gen.Route, t *tsTypes, pad string) {
	var params []string
	var url strings.Builder
	url.WriteByte('`')
	for _, s := range rt.Segments {
		url.WriteByte('/')
		if s.Kind == gen.SegLit {
			url.WriteString(s.Lit)
			continue
		}
		p := s.Param
		params = append(params, tsIdent(p.Name)+": "+tsParamType(p))
		if p.Rest || (p.Type.Pkg == "" && p.Type.Name != "string") {
			fmt.Fprintf(&url, "${%s}", tsIdent(p.Name))
		} else {
			fmt.Fprintf(&url, "${encodeURIComponent(%s)}", tsIdent(p.Name))
		}
	}
	if len(rt.Segments) == 0 {
		url.WriteByte('/')
	}
	url.WriteByte('`')
	path := url.String()
	if rt.Static() {
		path = strconv.Quote(path[1 : len(path)-1])
	}

	payload := "undefined"
	if body := rt.Body(); body != nil {
		typ := t.ref(gen.TypeRef{Pkg: body.Type.Pkg, Name: body.Type.Name}, ggen.In)
		if manyBody(body) {
			typ += "[]"
		}
		params = append(params, "body: "+typ)
		payload = "body"
	}
	params = append(params, "init?: RequestInit")

	if rt.Doc == "" {
		fmt.Fprintf(b, "%s/** %s %s */\n", pad, rt.Method, rt.Path)
	} else {
		fmt.Fprintf(b, "%s/**\n", pad)
		for line := range strings.SplitSeq(rt.Doc, "\n") {
			fmt.Fprintf(b, "%s\n", strings.TrimRight(pad+" * "+line, " "))
		}
		fmt.Fprintf(b, "%s *\n%s * %s %s\n%s */\n", pad, pad, rt.Method, rt.Path, pad)
	}

	call := fmt.Sprintf("t.none(%q, %s, %s, init)", rt.Method, path, payload)
	if r := rt.Result; r != nil {
		typ := t.ref(gen.TypeRef{Pkg: r.Pkg, Name: r.Name}, ggen.Out)
		if r.Slice {
			typ += "[]"
		}
		call = fmt.Sprintf("t.json<%s>(%q, %s, %s, init)", typ, rt.Method, path, payload)
	}
	fmt.Fprintf(b, "%s%s: (%s) => %s,\n", pad, lowerCamel(rt.Handler), strings.Join(params, ", "), call)
}

// tsParamType is what a path param takes. A named type is text on the wire.
func tsParamType(p *gen.Param) string {
	if p.Rest || p.Type.Pkg != "" {
		return "string"
	}
	return tsBuiltin(p.Type.Name)
}

func tsBuiltin(name string) string {
	switch name {
	case "string":
		return "string"
	case "bool":
		return "boolean"
	case "int", "int8", "int16", "int32", "int64",
		"uint", "uint8", "uint16", "uint32", "uint64",
		"float32", "float64":
		return "number"
	}
	return "unknown"
}

func lowerCamel(s string) string {
	if s == "" {
		return s
	}
	return strings.ToLower(s[:1]) + s[1:]
}

// tsIdent keeps a Go param name from clashing with the client's own names.
func tsIdent(s string) string {
	switch s {
	case "body", "init", "t":
		return s + "_"
	}
	return s
}
